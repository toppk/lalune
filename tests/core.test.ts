import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import {
  Body, GeoMoon, GeoVector, Observer, Equator, Horizon, KM_PER_AU,
} from 'astronomy-engine';
import { calculateMoon, calculateSky, lunarAxes, dot, cross, normalize, type Vec3 } from '../src/core.js';

const fixture = JSON.parse(readFileSync(new URL('./fixtures/nasa-2026.json', import.meta.url), 'utf8'));
const close = (actual: number, expected: number, tolerance: number, context: string) =>
  assert.ok(Math.abs(actual-expected) <= tolerance, `${context}: ${actual} vs ${expected} (tolerance ${tolerance})`);
const tuple = (v: {x: number; y: number; z: number}): Vec3 => [v.x, v.y, v.z];

test('geocentric geometry agrees with independent NASA SVS weekly ephemeris samples', () => {
  // These are external reference values, NOT snapshots generated by our code.
  // NASA's table is GEOCENTRIC; do not compare its distance directly to the
  // public API's observer-dependent topocentric distance. See docs/SCIENCE.md.
  for (const row of fixture.samples) {
    const date = new Date(row.time.replace(' UT', ' UTC'));
    const m = GeoMoon(date), s = GeoVector(Body.Sun, date, false);
    const v = normalize([-m.x, -m.y, -m.z]);
    const sun = normalize([s.x-m.x, s.y-m.y, s.z-m.z]);
    const body = lunarAxes(date).map(axis => dot(axis, v));
    close(Math.hypot(...tuple(m))*KM_PER_AU, row.distance, 60, `${row.time}: distance km`);
    close(Math.atan2(body[1], body[0])*180/Math.PI, row.subearth.lon, 0.02, `${row.time}: sub-Earth longitude degrees`);
    close(Math.asin(body[2])*180/Math.PI, row.subearth.lat, 0.02, `${row.time}: sub-Earth latitude degrees`);
    close(50*(1+dot(v,sun)), row.phase, 0.03, `${row.time}: illumination percentage points`);
    const subSun = lunarAxes(date).map(axis => dot(axis, sun));
    close(Math.atan2(subSun[1], subSun[0])*180/Math.PI, row.subsolar.lon, 0.02, `${row.time}: subsolar longitude degrees`);
    close(Math.asin(subSun[2])*180/Math.PI, row.subsolar.lat, 0.02, `${row.time}: subsolar latitude degrees`);
  }
});

test('topocentric horizon agrees with Astronomy Engine independent Equator/Horizon path', () => {
  // Different path through the dependency catches EQJ/EQD frame confusion,
  // west/east sign errors, and forgetting to subtract the terrestrial observer.
  for (const latitude of [-90, -33.8688, 0, 34.0522222, 40.7142778, 90]) {
    for (const longitude of [-118.2436667, -74.0059722, 0, 151.2093]) {
      const date = new Date('2026-10-30T11:00:00Z');
      const state = calculateMoon({ date, observer: { latitude, longitude } });
      const eq = Equator(Body.Moon, date, new Observer(latitude, longitude, 0), true, false);
      const expected = Horizon(date, new Observer(latitude, longitude, 0), eq.ra, eq.dec, '');
      close(state.altitudeDeg, expected.altitude, 0.002, 'geometric altitude degrees');
      close(state.azimuthDeg, expected.azimuth, 0.002, 'azimuth degrees');
      close(dot(state.viewDirection,state.upDirection), 0, 1e-12, 'camera up perpendicular to line of sight');
    }
  }
});

test('lunar axes remain orthonormal and right handed over the fixture year', () => {
  for (const row of fixture.samples) {
    const [x,y,z] = lunarAxes(new Date(row.time.replace(' UT',' UTC')));
    for (const axis of [x,y,z]) close(dot(axis,axis),1,1e-12,'unit axis');
    close(dot(x,y),0,1e-12,'perpendicular axes');
    close(dot(cross(x,y),z),1,1e-12,'right handed axes');
  }
});

test('NYC and LA have different viewing geometry at the same instant', () => {
  const date = new Date('2026-10-30T11:09:51Z');
  const ny = calculateMoon({date,observer:{latitude:40.7142778,longitude:-74.0059722}});
  const la = calculateMoon({date,observer:{latitude:34.0522222,longitude:-118.2436667}});
  assert.ok(Math.abs(ny.altitudeDeg-la.altitudeDeg)>5);
  assert.ok(Math.abs(ny.subObserver.longitudeDeg-la.subObserver.longitudeDeg)>0.05);
  const north = calculateMoon({date,observer:ny.observer,orientation:'north'});
  close(dot(ny.viewDirection,north.viewDirection),1,1e-12,'orientation does not change line of sight');
  assert.ok(dot(ny.upDirection,north.upDirection)<0.99);
});

test('solar altitude follows the observer and agrees with the Equator/Horizon path', () => {
  const date = new Date('2026-10-30T11:41:22Z');
  const locations = [
    {latitude:40.7142778,longitude:-74.0059722},
    {latitude:34.0522222,longitude:-118.2436667},
  ];
  const states = locations.map(observer => {
    const state = calculateMoon({date,observer});
    const earthObserver = new Observer(observer.latitude, observer.longitude, 0);
    const eq = Equator(Body.Sun, date, earthObserver, true, false);
    const expected = Horizon(date, earthObserver, eq.ra, eq.dec, '');
    close(state.sunAltitudeDeg, expected.altitude, 0.002, 'geometric solar altitude');
    return state;
  });
  assert.equal(calculateSky(states[0].sunAltitudeDeg).period,'Daytime');
  assert.equal(calculateSky(states[1].sunAltitudeDeg).period,'Night');
});

test('sky display follows USNO twilight thresholds and blends continuously', () => {
  assert.equal(calculateSky(-30).period, 'Night');
  assert.equal(calculateSky(-15).period, 'Astronomical twilight');
  assert.equal(calculateSky(-9).period, 'Nautical twilight');
  assert.equal(calculateSky(-3).period, 'Civil twilight');
  assert.equal(calculateSky(20).period, 'Daytime');
  assert.equal(calculateSky(-30).daylight, 0);
  assert.equal(calculateSky(20).daylight, 1);
  for (const altitude of [-18,-12,-6,0,10,45]) {
    const left = calculateSky(altitude-0.001), right = calculateSky(altitude+0.001);
    for (const index of [1,3,5]) {
      const channel = (color: string) => parseInt(color.slice(index,index+2),16);
      assert.ok(Math.abs(channel(left.color)-channel(right.color))<=1);
    }
    assert.ok(right.daylight >= left.daylight);
  }
  assert.throws(()=>calculateSky(NaN), /Sun altitude/);
});

test('invalid inputs fail clearly, without propagating NaNs into WebGL', () => {
  const observer = {latitude: 0, longitude: 0};
  assert.throws(()=>calculateMoon({observer,date:new Date('invalid')}), /date/);
  assert.throws(()=>calculateMoon({observer:{...observer,latitude:91}}), /Latitude/);
  assert.throws(()=>calculateMoon({observer:{...observer,longitude:NaN}}), /Longitude/);
  assert.throws(()=>calculateMoon({observer:{...observer,elevation:Infinity}}), /Elevation/);
});

test('New York and Los Angeles timezone displays follow IANA daylight-saving rules', () => {
  const hour = (date: string, timeZone: string) => new Intl.DateTimeFormat('en-US', {hour:'2-digit',hourCycle:'h23',timeZone}).format(new Date(date));
  assert.equal(hour('2026-07-01T12:00:00Z','America/New_York'),'08');
  assert.equal(hour('2026-01-01T12:00:00Z','America/New_York'),'07');
  assert.equal(hour('2026-07-01T12:00:00Z','America/Los_Angeles'),'05');
  assert.equal(hour('2026-01-01T12:00:00Z','America/Los_Angeles'),'04');
});
